import { fileURLToPath } from 'node:url';
const INDEX_PATH = fileURLToPath(new URL('../lib/index.js', import.meta.url));

process.env.DSH_HOME = '/tmp/vd-src-home';
const { rm } = await import('node:fs/promises');
await rm('/tmp/vd-src-home', { recursive: true, force: true });
const mod = await import(INDEX_PATH);
const routes = new Map();
const ctx = { connection: { fetch: { register: (r) => { routes.set(r.path, r); return () => {}; } } }, get: () => undefined, plugin: () => ({ dispose: () => {} }), desktopRuntime: { updates: { currentVersion: '2.0.17', canDownload: true, request: () => Promise.reject(new Error('x')) } }, logger: { info: () => {} }, effect: (fn) => { fn(); return () => {}; }, inject: (_d, cb) => { cb(ctx); return () => {}; } };
mod.apply(ctx);
await new Promise((r) => setTimeout(r, 150));
const call = async (p, body) => { const r = await routes.get(p).fetch(new Request(`http://x${p}`, { method: body ? 'POST' : 'GET', ...(body ? { body: JSON.stringify(body), headers: { 'content-type': 'application/json' } } : {}) })); return { s: r.status, d: await r.json().catch(() => null) }; };
let fail = 0;
const check = (l, ok, detail) => { console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${l}${detail ? ' — ' + detail : ''}`); if (!ok) fail += 1; };
const s0 = await call('/api/dsh-update-vd/sources');
check('默认只有预设源（无自定义）', s0.d.sources.skills.length === 2, s0.d.sources.skills.map((x) => x.label).join(', '));
const added = await call('/api/dsh-update-vd/sources/add', { kind: 'skills', address: 'https://github.com/anthropics/skills', label: '再加一次（重名测试）' });
check('重名地址被拒', added.d.ok === false, added.d.error);
const added2 = await call('/api/dsh-update-vd/sources/add', { kind: 'skills', address: 'https://github.com/obra/superpowers', label: '再加一次（重名测试）' });
check('同一仓库重名被拒', added2.d.ok === false, added2.d.error);
const added3 = await call('/api/dsh-update-vd/sources/add', { kind: 'mcp', address: 'https://registry.modelcontextprotocol.io/v0/servers' });
check('重复的注册表地址被拒', added3.d.ok === false, added3.d.error);
const ok = await call('/api/dsh-update-vd/sources/add', { kind: 'skills', address: 'vercel/ai', label: 'Vercel AI' });
check('新增一个地址', ok.d.ok === true, JSON.stringify(ok.d.entry));
const s1 = await call('/api/dsh-update-vd/sources');
check('下拉里出现了', s1.d.sources.skills.some((x) => x.id === ok.d.entry.id), s1.d.sources.skills.map((x) => x.label).join(' | '));
const bad = await call('/api/dsh-update-vd/sources/add', { kind: 'skills', address: '这不是地址' });
check('乱填被拒', bad.d.ok === false, bad.d.error);
const search = await call('/api/dsh-update-vd/skills/search', { sourceId: ok.d.entry.id, query: '', limit: 5 });
check('用自定义源能搜', search.d.ok === true, `命中 ${search.d.results?.length}（仓库共 ${search.d.source?.total} 个 SKILL.md）`);
const removed = await call('/api/dsh-update-vd/sources/remove', { kind: 'skills', id: ok.d.entry.id });
check('删除自定义地址', removed.d.ok === true && !removed.d.sources.skills.some((x) => x.id === ok.d.entry.id));
const pres = await call('/api/dsh-update-vd/sources/remove', { kind: 'skills', id: 'anthropics-skills' });
check('预设源删不掉（有提示）', pres.d.ok === false, pres.d.error);
const listed2 = await call('/api/dsh-update-vd/skills/search', { sourceId: 'anthropics-skills', query: '', limit: 3 });
check('预设源搜索仍正常', listed2.d.ok === true && listed2.d.results.length === 3);
console.log(fail === 0 ? '\n全部通过' : `\n${fail} 项失败`);
await rm('/tmp/vd-src-home', { recursive: true, force: true });
process.exit(fail === 0 ? 0 : 1);
